-- ============================================================
-- 电子圣诞树 · 共享祝福池建表脚本
-- 在 Supabase 控制台 → SQL Editor → New query，整段粘贴运行
-- ============================================================

-- 1. 建表
create table if not exists public.wishes (
  id          bigint generated by default as identity primary key,
  content     text        not null,
  created_at  timestamptz not null default now(),

  -- 长度约束：前端限制 18 字，这里放宽到 40 兜住异常请求
  constraint wishes_content_len check (char_length(content) between 1 and 40)
);

-- 2. 索引：按时间倒序取最新 N 条
create index if not exists wishes_created_at_idx
  on public.wishes (created_at desc);

-- 3. 开启行级安全（RLS）—— 这是安全的关键
alter table public.wishes enable row level security;

-- 4. 策略：任何人都能读
drop policy if exists "anyone can read wishes" on public.wishes;
create policy "anyone can read wishes"
  on public.wishes
  for select
  to anon
  using (true);

-- 5. 策略：任何人都能插入，但只能插入合法长度的内容
--    注意：没给 update / delete 权限，所以写进去的祝福删不掉也改不了
drop policy if exists "anyone can insert wishes" on public.wishes;
create policy "anyone can insert wishes"
  on public.wishes
  for insert
  to anon
  with check (
    char_length(content) between 1 and 40
    and content !~ '^\s*$'
  );

-- 6. 只把必要字段暴露给 anon 角色
revoke all on public.wishes from anon;
grant select (content, created_at) on public.wishes to anon;
grant insert (content) on public.wishes to anon;
grant usage on sequence public.wishes_id_seq to anon;

