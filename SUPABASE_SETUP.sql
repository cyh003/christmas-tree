-- 电子圣诞树 · 共享祝福池
-- 用法：Supabase → SQL Editor → New query → 全选粘贴本文件内容 → Run
-- 注意：要复制「文件内容」，不是复制文件路径

create table if not exists public.wishes (
  id         bigint generated by default as identity primary key,
  content    text not null,
  created_at timestamptz not null default now(),
  constraint wishes_content_len check (char_length(content) between 1 and 40)
);

create index if not exists wishes_created_at_idx
  on public.wishes (created_at desc);

-- 开启行级安全：没有策略就谁也读不到
alter table public.wishes enable row level security;

-- 策略一：任何人都能读
drop policy if exists "anyone can read wishes" on public.wishes;
create policy "anyone can read wishes"
  on public.wishes for select to anon using (true);

-- 策略二：任何人都能插入，但只能 1~40 字
drop policy if exists "anyone can insert wishes" on public.wishes;
create policy "anyone can insert wishes"
  on public.wishes for insert to anon
  with check (char_length(content) between 1 and 40 and content !~ '^\s*$');

-- 只给读写权限，不给 update / delete：写进去的祝福改不了也删不掉
grant select, insert on public.wishes to anon;

-- 验证
select count(*) as total_wishes from public.wishes;
